function complete_flag = cmig_check_fsurf_files(fspath)
%function complete_flag = cmig_check_fsurf_files(fspath)
%
% Purpose: check whether FreeSurfer recon is complete
%
%   Checks for existence of key output files:
%     mri/aseg.mgz
%     mri/orig.mgz
%     mri/nu.mgz
%     surf/lh.orig
%     surf/rh.orig
%     surf/lh.white
%     surf/rh.white
%     surf/lh.sphere.reg
%     surf/rh.sphere.reg
%     surf/lh.thickness
%     surf/rh.thickness
%     surf/lh.pial
%     surf/rh.pial
%     surf/lh.area
%     surf/rh.area
%     surf/lh.sulc
%     surf/rh.sulc
%     label/lh.aparc.annot
%     label/rh.aparc.annot
%     label/lh.aparc.a2009s.annot
%     label/rh.aparc.a2009s.annot
%
% Required input:
%   fspath: full path of FreeSurfer recon output directory
%
% Created:  04/24/2026 by Don Hagler
% Prev Mod: 04/24/2026 by Don Hagler
% Prev Mod: 07/10/2026 by Don Hagler
% Prev Mod: 08/13/2026 by Don Hagler
% Last Mod: 08/20/2026 by Don Hagler
%

complete_flag = 1;
fnamelist = {...
  sprintf('%s/mri/aseg.mgz',fspath)...
  sprintf('%s/mri/ribbon.mgz',fspath)...
  sprintf('%s/mri/orig.mgz',fspath)...
  sprintf('%s/mri/nu.mgz',fspath)...
  sprintf('%s/surf/lh.orig',fspath)...
  sprintf('%s/surf/rh.orig',fspath)...
  sprintf('%s/surf/lh.white',fspath)...
  sprintf('%s/surf/rh.white',fspath)...
  sprintf('%s/surf/lh.sphere.reg',fspath)...
  sprintf('%s/surf/rh.sphere.reg',fspath)...
  sprintf('%s/surf/lh.thickness',fspath)...
  sprintf('%s/surf/rh.thickness',fspath)...
  sprintf('%s/surf/lh.pial',fspath)...
  sprintf('%s/surf/rh.pial',fspath)...
  sprintf('%s/surf/lh.area',fspath)...
  sprintf('%s/surf/rh.area',fspath)...
  sprintf('%s/surf/lh.sulc',fspath)...
  sprintf('%s/surf/rh.sulc',fspath)...
  sprintf('%s/label/lh.aparc.annot',fspath)...
  sprintf('%s/label/rh.aparc.annot',fspath)...
  sprintf('%s/label/lh.aparc.a2009s.annot',fspath)...
  sprintf('%s/label/rh.aparc.a2009s.annot',fspath)...
};
for f=1:length(fnamelist)
  if ~exist(fnamelist{f},'file')
    complete_flag = 0;
    break;
  end
end

return;


